def ensure_conftest(target_path: str, transport: Transport | None = None) -> bool:
    """Write conftest_zsiga.py if it is missing.

    Returns True iff a new file was written.
    """
    transport = transport or LocalTransport()
    tests_dir = os.path.join(target_path, "tests")
    transport.run_shell(f"mkdir -p '{tests_dir}'", timeout=5)
    conf_path = os.path.join(tests_dir, "conftest_zsiga.py")
    existing = read_file(conf_path, transport)
    if existing is not None:
        return False
    transport.run_shell(
        f"cat > '{conf_path}' <<'ZSIGA_CONFTEST_EOF'\n{CONFTEST_ZSIGA}\nZSIGA_CONFTEST_EOF",
        timeout=10,
    )
    return True


