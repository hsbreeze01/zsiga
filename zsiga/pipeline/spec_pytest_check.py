def _py_compile_ok(source_text: str) -> tuple[bool, str]:
    """Return (ok, error_message). Uses py_compile via a tmpfile."""
    with tempfile.NamedTemporaryFile(
        suffix=".py", mode="w", delete=False, encoding="utf-8",
    ) as f:
        f.write(source_text)
        tmp = f.name
    try:
        try:
            py_compile.compile(tmp, doraise=True)
            return True, ""
        except py_compile.PyCompileError as exc:  # pragma: no cover - defensive
            return False, str(exc)
    finally:
        try:
            os.unlink(tmp)
        except OSError:  # pragma: no cover
            pass


_TESTABLE_LINE_RE = re.compile(
    r"(?P<prefix>^[\s*\-]*\*\*testable\*\*\s*:?\s*)"
    r"(?P<value>true)"
    r"(?P<rest>.*)$",
    re.IGNORECASE | re.MULTILINE,
)


def _demote_in_spec(spec_text: str, scenario_name: str, reason: str) -> str:
    """Replace the *first* ``testable: true`` line under ``scenario_name``
    with ``testable: false  <!-- demoted by zsiga: <reason> -->``.

    Conservative: only mutates the testable line, leaves target / Given /
    When / Then untouched so REVIEW can read the original intent.
    """
    # Find the scenario block by its heading
    heading_re = re.compile(
        rf"^(#{{3,6}})\s*Scenario\s*:\s*{re.escape(scenario_name)}\s*$",
        re.MULTILINE,
    )
    m = heading_re.search(spec_text)
    if not m:
        return spec_text
    block_start = m.end()
    # Block ends at next scenario heading (any depth ≥ 3) or EOF
    next_h = re.compile(r"^#{3,6}\s*Scenario\s*:", re.MULTILINE)
    nm = next_h.search(spec_text, block_start)
    block_end = nm.start() if nm else len(spec_text)

    block = spec_text[block_start:block_end]
    new_block, n = _TESTABLE_LINE_RE.subn(
        rf"\g<prefix>false  <!-- demoted by zsiga: {reason} -->",
        block,
        count=1,
    )
    if n == 0:
        return spec_text
    return spec_text[:block_start] + new_block + spec_text[block_end:]


@dataclass
class SpecValidation:
    """Per-spec record."""

    spec_filename: str
    scenarios_total: int = 0
    scenarios_testable_declared: int = 0
    scenarios_testable_validated: int = 0
    scenarios_demoted: list[tuple[str, str]] = field(default_factory=list)
    """Each tuple is ``(scenario_name, reason)``."""
    test_file_path: str | None = None
    test_file_present: bool = False
    test_file_compile_ok: bool = False


@dataclass
class SpecPytestReport:
    change_id: str
    target_path: str
    conftest_written: bool = False
    spec_validations: list[SpecValidation] = field(default_factory=list)

    @property
    def total_testable_declared(self) -> int:
        return sum(v.scenarios_testable_declared for v in self.spec_validations)

    @property
    def total_testable_validated(self) -> int:
        return sum(v.scenarios_testable_validated for v in self.spec_validations)

    @property
    def total_demoted(self) -> int:
        return sum(len(v.scenarios_demoted) for v in self.spec_validations)

    def summary_line(self) -> str:
        return (
            f"spec→pytest: {self.total_testable_validated}/"
            f"{self.total_testable_declared} testable scenarios validated, "
            f"{self.total_demoted} demoted, "
            f"conftest={'written' if self.conftest_written else 'present'}"
        )


def validate_testable_artifacts(
    change_dir: str,
    target_path: str,
    transport: Transport | None = None,
    *,
    allow_inferred_contract: bool = False,
) -> SpecPytestReport:
    """Walk specs, validate companion pytest files, demote on failure.

    Side effects: rewrites individual spec markdown files when a
    scenario must be demoted, deletes broken pytest files, optionally
    writes a fresh conftest_zsiga.py.

    Phase 6 — when ``allow_inferred_contract`` is ``False`` (default),
    any scenario marked ``testable: true`` without a ``contract:`` block
    is demoted to Layer 2; this avoids the 29% L1-FAIL signature-
    mismatch failure mode observed when ENRICH guesses signatures from
    the When-clause text. Pass ``allow_inferred_contract=True`` to
    accept the legacy inferred-signature path.
    """
    transport = transport or LocalTransport()
    change_id = os.path.basename(os.path.normpath(change_dir))
    report = SpecPytestReport(change_id=change_id, target_path=target_path)

    specs_dir = os.path.join(change_dir, "specs")
    spec_files = list_files_recursive(specs_dir, "*.md", transport)
    if not spec_files:
        return report

    report.conftest_written = ensure_conftest(target_path, transport)

    for spec_path in spec_files:
        spec_filename = os.path.basename(spec_path)
        spec_text = read_file(spec_path, transport) or ""
        scenarios = parse_spec(spec_text)
        validation = SpecValidation(
            spec_filename=spec_filename,
            scenarios_total=len(scenarios),
        )

        testable = [s for s in scenarios if s.testable]
        validation.scenarios_testable_declared = len(testable)

        if not testable:
            report.spec_validations.append(validation)
            continue

        # Phase 6: demote testable scenarios that lack an explicit contract,
        # unless the project opted into the legacy inferred-signature path.
        if not allow_inferred_contract:
            no_contract = [s for s in testable if s.contract is None]
            if no_contract:
                updated_text = spec_text
                for sc in no_contract:
                    updated_text = _demote_in_spec(
                        updated_text, sc.name,
                        "missing contract field (Phase 6 strict mode)",
                    )
                    validation.scenarios_demoted.append(
                        (sc.name, "missing contract"),
                    )
                transport.run_shell(
                    f"cat > '{spec_path}' <<'ZSIGA_DEMOTE_EOF'\n"
                    f"{updated_text}\n"
                    f"ZSIGA_DEMOTE_EOF",
                    timeout=10,
                )
                spec_text = updated_text
                # Re-derive testable list now that some scenarios were demoted
                scenarios = parse_spec(spec_text)
                testable = [s for s in scenarios if s.testable]
                if not testable:
                    report.spec_validations.append(validation)
                    continue

        # Compute expected test file path
        test_path = expected_test_path(target_path, change_id, spec_filename)
        validation.test_file_path = test_path
        test_source = read_file(test_path, transport)

        if test_source is None:
            # ENRICHER didn't generate the file — demote ALL testable
            # scenarios in this spec.
            updated_text = spec_text
            for sc in testable:
                updated_text = _demote_in_spec(
                    updated_text, sc.name,
                    "test file missing after ENRICH",
                )
                validation.scenarios_demoted.append(
                    (sc.name, "test file missing"),
                )
            transport.run_shell(
                f"cat > '{spec_path}' <<'ZSIGA_DEMOTE_EOF'\n"
                f"{updated_text}\n"
                f"ZSIGA_DEMOTE_EOF",
                timeout=10,
            )
            report.spec_validations.append(validation)
            continue

        validation.test_file_present = True
        ok, err = _py_compile_ok(test_source)
        if not ok:
            # Syntax error — delete file and demote scenarios.
            transport.run_shell(f"rm -f '{test_path}'", timeout=5)
            updated_text = spec_text
            for sc in testable:
                updated_text = _demote_in_spec(
                    updated_text, sc.name,
                    f"test file py_compile failed: {err.splitlines()[0][:100]}",
                )
                validation.scenarios_demoted.append((sc.name, "compile failed"))
            transport.run_shell(
                f"cat > '{spec_path}' <<'ZSIGA_DEMOTE_EOF'\n"
                f"{updated_text}\n"
                f"ZSIGA_DEMOTE_EOF",
                timeout=10,
            )
            report.spec_validations.append(validation)
            continue

        validation.test_file_compile_ok = True
        validation.scenarios_testable_validated = len(testable)
        report.spec_validations.append(validation)

    return report
